#!/usr/bin/env python3
"""Generate src/PoEtry/Tables.fs from PoB-PoE2's Data/Misc.lua.

PoB's Misc.lua is itself exported from the game's .dat files (DefaultMonsterStats,
GameConstants), so these are game data, not PoB estimates.
Usage: gen_tables.py <path/to/Misc.lua> > src/PoEtry/Tables.fs
"""
import re, sys

src = open(sys.argv[1]).read()

def table(name):
    m = re.search(r"data\.%s = \{([^}]*)\}" % name, src)
    return [float(x) for x in m.group(1).replace(" ", "").split(",") if x]

def block(name):
    m = re.search(r"data\.%s = \{(.*?)\n\}" % name, src, re.S)
    return dict((k, float(v)) for k, v in re.findall(r'\["([^"]+)"\] = (-?[\d.]+)', m.group(1)))

tables = {
    "monsterLife": "monsterLifeTable",
    "monsterArmour": "monsterArmourTable",
    "monsterEvasion": "monsterEvasionTable",
    "monsterAccuracy": "monsterAccuracyTable",
    "monsterDamage": "monsterDamageTable",
    "monsterAilmentThreshold": "monsterAilmentThresholdTable",
    "monsterPoiseThreshold": "monsterPoiseThresholdTable",
}
gc = block("gameConstants")
mc = block("monsterConstants")

out = ["// GENERATED by tools/gen_tables.py from PoB-PoE2 Data/Misc.lua (game .dat exports). Do not edit.",
       "namespace PoEtry", "", "module Tables ="]
for fs, lua in tables.items():
    vals = table(lua)
    out.append("    /// Indexed by monster level - 1 (level 1..%d)." % len(vals))
    out.append("    let %s = [| %s |]" % (fs, "; ".join(repr(v) for v in vals)))
    out.append("")
out.append("    /// GameConstants.dat")
out.append("    let gameConstants =")
out.append("        Map.ofList [")
for k, v in gc.items():
    out.append('            "%s", %r' % (k.strip(), v))
out.append("        ]")
out.append("")
out.append("    /// Metadata/Monsters/Monster.ot")
out.append("    let monsterConstants =")
out.append("        Map.ofList [")
for k, v in mc.items():
    out.append('            "%s", %r' % (k, v))
out.append("        ]")
print("\n".join(out))
