#!/usr/bin/env python3
"""Generate src/PoEsie/RarityData.fs from game tables exported by pathofexile-dat.

Reads tables/English/{Mods,Stats}.json and collects the stats of the MonsterMagicN /
MonsterRareN / MonsterUniqueN mods, the rarity mods every magic/rare/unique monster has.
Usage: gen_rarity.py <tables dir> > src/PoEsie/RarityData.fs
"""
import json, re, sys

d = sys.argv[1]
stats = json.load(open(d + "/Stats.json"))
mods = json.load(open(d + "/Mods.json"))
out = {"Magic": {}, "Rare": {}, "Unique": {}}
for m in mods:
    g = re.fullmatch(r"Monster(Magic|Rare|Unique)\d+", m["Id"])
    if not g:
        continue
    for k in range(1, 7):
        s = m.get("Stat%d" % k)
        if s is None:
            continue
        v = m["Stat%dValue" % k]
        v = v[0] if isinstance(v, list) else v
        out[g.group(1)][stats[s]["Id"]] = v

print("// GENERATED by tools/gamefiles/gen_rarity.py from the game's Mods.dat (MonsterMagicN/RareN/UniqueN). Do not edit.")
print("namespace PoEsie")
print()
print("module RarityData =")
print("    /// Stats every monster of the rarity has: (rarity, stat id, value).")
print("    let stats =")
print("        [")
for r, kv in out.items():
    for k, v in sorted(kv.items()):
        print('          "%s", "%s", %r' % (r, k, float(v)))
print("        ]")
