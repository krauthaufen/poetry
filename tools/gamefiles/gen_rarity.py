#!/usr/bin/env python3
"""Generate src/PoEtry/RarityData.fs from game tables exported by pathofexile-dat.

Reads tables/English/{Mods,Stats,DefaultMonsterStats}.json and collects the stats of the MonsterMagicN /
MonsterRareN / MonsterUniqueN mods, the rarity mods every magic/rare/unique monster has.
Usage: gen_rarity.py <tables dir> > src/PoEtry/RarityData.fs
"""
import json, re, sys

d = sys.argv[1]
stats = json.load(open(d + "/Stats.json"))
mods = json.load(open(d + "/Mods.json"))
out = {"Magic": {}, "Rare": {}, "Unique": {}}
for m in mods:
    g = re.fullmatch(r"Monster(Magic|Rare|Unique)\d+", m["Id"])
    if not g:
        continue
    for k in range(1, 7):
        s = m.get("Stat%d" % k)
        if s is None:
            continue
        v = m["Stat%dValue" % k]
        v = v[0] if isinstance(v, list) else v
        out[g.group(1)][stats[s]["Id"]] = v

print("// GENERATED by tools/gamefiles/gen_rarity.py from the game's Mods.dat (MonsterMagicN/RareN/UniqueN). Do not edit.")
print("namespace PoEtry")
print()
print("module RarityData =")
print("    /// Stats every monster of the rarity has: (rarity, stat id, value).")
print("    let stats =")
print("        [")
for r, kv in out.items():
    for k, v in sorted(kv.items()):
        print('          "%s", "%s", %r' % (r, k, float(v)))
print("        ]")

# DefaultMonsterStats LeechResistance (permyriad) by monster level
levels = json.load(open(d + "/DefaultMonsterStats.json"))
print()
print("    /// Leech resistance in % by monster level - 1 (DefaultMonsterStats LeechResistance; rare and")
print("    /// unique monsters have the same).")
print("    let leechResistance = [| %s |]" % "; ".join(repr(r["LeechResistance"] / 100.0) for r in levels))
print()
print("    /// % more damage a minion of that level - 1 deals with hits and ailments against monsters that")
print("    /// are not unique (DefaultMonsterStats MoreDamageAgainstNonUnique).")
print("    let minionMoreAgainstNonUnique = [| %s |]" % "; ".join(repr(float(r["MoreDamageAgainstNonUnique"])) for r in levels))
print()
print("    /// % more elemental and chaos damage a monster of that level - 1 deals (DefaultMonsterStats")
print("    /// MoreElementalDamage, MoreChaosDamage: the stats non_player_minion_elemental_damage_+%_final_from_monster_level")
print("    /// and ..._chaos_...).")
print("    let moreElementalDamage = [| %s |]" % "; ".join(repr(float(r["MoreElementalDamage"])) for r in levels))
print("    let moreChaosDamage = [| %s |]" % "; ".join(repr(float(r["MoreChaosDamage"])) for r in levels))
