#!/usr/bin/env python3
"""Generate src/PoEtry/RareModsData.fs from game tables exported by pathofexile-dat.

Rare monster modifiers: the monster mods (Domain 3, prefix or suffix) a plain rare monster
can roll (spawn weight of the "default" tag above zero; Abyss, boss-only and other special
mods have none), with their family (a rare has at most one mod of a family) and the stats of
their "PlayerMonster..." twin, which is what a player gains from them ("When you kill a Rare
monster, you gain its Modifiers").
Usage: gen_rare_mods.py <tables dir> > src/PoEtry/RareModsData.fs
"""
import json, sys

d = sys.argv[1]
stats = json.load(open(d + "/Stats.json"))
mods = json.load(open(d + "/Mods.json"))
tags = json.load(open(d + "/Tags.json"))
byId = {m["Id"]: m for m in mods}


def statsOf(m):
    out = []
    for k in range(1, 7):
        s = m.get("Stat%d" % k)
        if s is None:
            continue
        v = m["Stat%dValue" % k]
        v = v[0] if isinstance(v, list) else v
        out.append((stats[s]["Id"], float(v)))
    return out


rows = []
for m in mods:
    if m["Domain"] != 3 or m["GenerationType"] not in (1, 2) or not m["Id"].startswith("Monster"):
        continue
    weights = {tags[t]["Id"]: w for t, w in zip(m["SpawnWeight_Tags"], m["SpawnWeight_Values"])}
    weight = weights.get("default", 0)
    player = byId.get("Player" + m["Id"])
    if weight <= 0 or player is None:
        continue
    family = m["Families"][0] if m["Families"] else -1
    rows.append((m["Id"], m["Name"], m["Level"], family, float(weight), statsOf(player)))

print("// GENERATED by tools/gamefiles/gen_rare_mods.py from the game's Mods.dat (rare monster mods). Do not edit.")
print("namespace PoEtry")
print()
print("module RareModsData =")
print("    /// (mod id, name, lowest monster level, family, spawn weight, stats a player gains from it)")
print("    let mods : (string * string * int * int * float * (string * float) list) list =")
print("        [")
for i, n, lvl, fam, w, ss in rows:
    s = "; ".join('"%s", %r' % (k, v) for k, v in ss)
    print('          "%s", "%s", %d, %d, %r, [ %s ]' % (i, n.replace('"', '\\"'), lvl, fam, w, s))
print("        ]")
