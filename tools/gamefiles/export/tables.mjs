#!/usr/bin/env node
// Tables.fs (monster life, armour, ... by level, GameConstants, Monster.ot constants) straight from the game.
// Replaces tools/gen_tables.py, which reads PoB's Data/Misc.lua (PoB's Export/Scripts/miscdata.lua).
// Usage: node export/tables.mjs [out file = <repo>/out/generated/Tables.fs]
import * as fs from 'node:fs';
import * as path from 'node:path';
import { openGame, GAMEFILES_DIR } from './lib/game.mjs';

// Python's repr of a float, which is what gen_tables.py writes
function pyFloat(v) {
  if (Number.isInteger(v)) return v.toFixed(1);
  const s = String(v);
  return s.includes('e') ? s.replace(/e([+-])(\d)$/, 'e$10$2') : s;
}
// Lua writes numbers with 14 significant digits (tostring), and that is what Misc.lua has
const lua = v => Number(v.toPrecision(14));

/** A "Stats { a = 1 }" block of an .ot file: [[key, value]] in file order. */
export function otBlock(text, blocks) {
  const out = [];
  let inside = false;
  for (const line of text.split(/[\r\n]+/)) {
    if (blocks.some(b => line.startsWith(b))) inside = true;
    else if (inside && line.startsWith('}')) inside = false;
    else if (inside && line.includes('=')) {
      const m = line.replace(/\s+/g, '').match(/^(.*?)=(.+)$/);
      if (m && m[1] !== '' && /^-?[\d.]+$/.test(m[2])) out.push([m[1], Number(m[2])]);
    }
  }
  return out;
}

export function generate(game) {
  const dms = game.table('DefaultMonsterStats');
  const tables = [
    ['monsterLife', r => r.MonsterLife], ['monsterArmour', r => r.Armour], ['monsterEvasion', r => r.Evasion],
    ['monsterAccuracy', r => r.Accuracy], ['monsterDamage', r => lua(r.Damage)], ['monsterAilmentThreshold', r => r.AilmentThreshold],
    ['monsterPoiseThreshold', r => r.PoiseThreshold],
    ['allyLife', r => r.AllyLife], ['allyDamage', r => lua(r.MinionDamage)],   // PoB: MinionLife, MinionDamage
  ];
  const out = ['// GENERATED by tools/gamefiles/export/tables.mjs from the game files (DefaultMonsterStats, MinionGemLevelScaling, GameConstants, Monster.ot). Do not edit.',
    'namespace PoEtry', '', 'module Tables ='];
  const arr = (name, vals, by) => {
    out.push(`    /// Indexed by ${by} - 1 (1..${vals.length}).`);
    out.push(`    let ${name} = [| ${vals.map(pyFloat).join('; ')} |]`);
    out.push('');
  };
  for (const [name, f] of tables) arr(name, dms.map(f), 'monster level');
  arr('minionLevel', game.table('MinionGemLevelScaling').map(r => r.MinionLevel), 'gem level');
  out.push('    /// GameConstants.dat', '    let gameConstants =', '        Map.ofList [');
  const seen = new Map();
  for (const r of game.table('GameConstants')) seen.set(r.Id.trim(), lua(r.Value / r.Divisor));   // a repeated id: the last one, as in a Lua table
  for (const [k, v] of seen) out.push(`            "${k}", ${pyFloat(v)}`);
  out.push('        ]', '', '    /// Metadata/Monsters/Monster.ot', '    let monsterConstants =', '        Map.ofList [');
  const ot = game.readText('Metadata/Monsters/Monster.ot');
  if (ot === null) throw new Error('missing Metadata/Monsters/Monster.ot');
  const mc = new Map(otBlock(ot, ['Stats']));
  for (const [k, v] of mc) out.push(`            "${k}", ${pyFloat(v)}`);
  out.push('        ]');
  return out.join('\n') + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const file = path.resolve(process.argv[2] || path.join(GAMEFILES_DIR, '..', '..', 'out', 'generated', 'Tables.fs'));
  const game = await openGame();
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, generate(game));
  console.log('wrote ' + file);
}
